def test_27_failed_infrastructure_response_is_mapped_correctly(seed_data, db_session):
    """27. Infrastructure failures map to 429, 504, 502 while preserving FAILED DB record."""
    d = seed_data

    # Rate limit -> 429
    with patch("app.services.verification_service.github_analyzer.analyze_repository", side_effect=HTTPException(429, "Rate limit")):
        res_429 = client.post(
            f"/api/v1/roadmap/{d['roadmap'].id}/milestones/{d['milestone'].id}/verify",
            headers={
                "X-User-Id": str(d["candidate"].id),
                "Authorization": f"Bearer {SENTINEL_PAT}",
            },
            json={"repository_id": str(d["repo"].id)},
        )
        assert res_429.status_code == 429

    # Timeout -> 504
    with patch("app.services.verification_service.github_analyzer.analyze_repository", side_effect=httpx.TimeoutException("Timeout")):
        res_504 = client.post(
            f"/api/v1/roadmap/{d['roadmap'].id}/milestones/{d['milestone'].id}/verify",
            headers={
                "X-User-Id": str(d["candidate"].id),
                "Authorization": f"Bearer {SENTINEL_PAT}",
            },
            json={"repository_id": str(d["repo"].id)},
        )
        assert res_504.status_code == 504

    # Upstream 502 -> 502
    with patch("app.services.verification_service.github_analyzer.analyze_repository", side_effect=httpx.RequestError("Upstream bad gateway")):
        res_502 = client.post(
            f"/api/v1/roadmap/{d['roadmap'].id}/milestones/{d['milestone'].id}/verify",
            headers={
                "X-User-Id": str(d["candidate"].id),
                "Authorization": f"Bearer {SENTINEL_PAT}",
            },
            json={"repository_id": str(d["repo"].id)},
        )
        assert res_502.status_code == 502

    # Verify FAILED record was persisted in DB
    failed_rec = (
        db_session.query(MilestoneVerification)
        .filter(MilestoneVerification.milestone_id == d["milestone"].id, MilestoneVerification.status == "FAILED")
        .first()
    )
    assert failed_rec is not None


