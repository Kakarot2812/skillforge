def test_01_authenticated_candidate_can_verify_own_milestone(seed_data):
    """1. Authenticated candidate can verify own roadmap milestone and receives typed VERIFIED response."""
    d = seed_data
    with patch("app.services.verification_service.github_analyzer.fetch_repo_tree", return_value=MOCK_TREE_VERIFIED), \
         patch("app.services.verification_service.github_analyzer.fetch_file_content", side_effect=lambda fn, p, token=None: MOCK_FILES_VERIFIED.get(p)), \
         patch("app.services.verification_service.github_analyzer.analyze_repository", return_value=([], set())):

        res = client.post(
            f"/api/v1/roadmap/{d['roadmap'].id}/milestones/{d['milestone'].id}/verify",
            headers={
                "X-User-Id": str(d["candidate"].id),
                "Authorization": f"Bearer {SENTINEL_PAT}",
            },
            json={"repository_id": str(d["repo"].id)},
        )

        assert res.status_code == 200
        data = res.json()
        assert data["status"] == "VERIFIED"
        assert data["confidence"] is not None
        assert data["confidence"] >= 0.85
        assert data["milestone_status"] == "VERIFIED"
        assert data["commit_sha"] == "a1b2c3d4e5f67890123456789abcdef012345678"
        assert data["milestone_id"] == str(d["milestone"].id)
        assert data["roadmap_id"] == str(d["roadmap"].id)
        assert data["user_id"] == str(d["candidate"].id)


